/** Closed execution modes accepted by the import service. */
export type ImportMode = 'merge' | 'overwrite' | 'dry-run';

/** A single entity operation result */
export interface ImportEntityResult {
  /** Closed entity category. */
  type: string;
  /** Public natural-key component used to identify the entity. */
  slug: string;
  /** Human-readable entity label. */
  name: string;
  /** Mutable fields changed or planned by the operation. */
  changes?: string[];
  /** Indicates that a committed confidential-client create would issue a credential. */
  credentialWillBeGenerated?: boolean;
}

/** A skipped entity with reason */
export interface ImportSkippedResult {
  /** Closed entity category. */
  type: string;
  /** Public natural-key component used to identify the entity. */
  slug: string;
  /** Stable explanation for the intentional no-op. */
  reason: string;
}

/** An import error for a specific entity */
export interface ImportErrorResult {
  /** Closed entity category. */
  type: string;
  /** Public natural-key component used to identify the entity. */
  slug: string;
  /** Legacy internal diagnostic, never serialized by a successful import. */
  error: string;
}

/** Client credentials generated during import (shown once, never stored in plaintext) */
export interface ImportClientCredentials {
  /** Public client display name. */
  clientName: string;
  /** Generated public client identifier, present only after commit. */
  clientId?: string;
  /** OIDC client category. */
  clientType: 'confidential' | 'public';
  /** Dry-run indication which never contains generated credential material. */
  credentialWillBeGenerated?: boolean;
  /** Raw secret — only present on create for confidential clients */
  secretPlaintext?: string;
  /** DB row ID of the generated secret */
  secretId?: string;
  /** Optional label for the generated secret. */
  secretLabel?: string;
  /** Optional expiry for the generated secret. */
  secretExpiresAt?: string;
}

/** Full import result */
export interface ImportResult {
  /** Execution mode applied to the manifest. */
  mode: ImportMode;
  /** Entities created or planned for creation. */
  created: ImportEntityResult[];
  /** Entities updated or planned for update. */
  updated: ImportEntityResult[];
  /** Existing entities intentionally left unchanged. */
  skipped: ImportSkippedResult[];
  /** Present only on legacy rejected responses; successful imports omit error details. */
  errors?: ImportErrorResult[];
  /** Credentials generated by committed confidential-client creates. */
  credentials: ImportClientCredentials[];
}

/** Closed public failure codes emitted by the import boundary. */
export type ImportFailureCode =
  'import_manifest_invalid' | 'import_plan_rejected' | 'import_execution_failed';

/**
 * Sanitized import failure which retains no manifest values or dependency diagnostics.
 */
export class ImportOperationError extends Error {
  /** Stable public error discriminator. */
  public readonly code: ImportFailureCode;

  /** Server-created identifier used to correlate private operational diagnostics. */
  public readonly correlationId: string;

  /** Recommended public HTTP status. */
  public readonly status: 400 | 409 | 503;

  /**
   * Create a minimal import failure.
   *
   * @param code - Stable public failure category.
   * @param status - Recommended HTTP status for the route boundary.
   * @param correlationId - Optional existing server correlation identifier.
   */
  public constructor(code: ImportFailureCode, status: 400 | 409 | 503, correlationId?: string) {
    super('Import request could not be completed');
    this.name = 'ImportOperationError';
    this.code = code;
    this.status = status;
    this.correlationId = correlationId ?? randomUUID();
  }
}

/** Mutable transaction-local result which is never serialized before successful commit. */
interface ImportAccumulator extends ImportResult {
  errors: ImportErrorResult[];
}

